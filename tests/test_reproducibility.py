"""Comparison of regenerated outputs with committed ones (E22)."""

import gzip
import json

from src.analysis.reproducibility import compare_file, strip_json, strip_markdown, summarize


def test_identical_and_missing():
    assert compare_file("a.csv", b"x,y\n1,2\n", b"x,y\n1,2\n")["status"] == "identical"
    assert compare_file("a.csv", b"x\n", None)["status"] == "missing"


def test_json_masks_run_metadata_only():
    old = {"run_info": {"git_commit": "a"}, "scores": [1.0, {"seconds": 3, "value": 2}], "timestamp_utc": "t1"}
    new = {"run_info": {"git_commit": "b"}, "scores": [1.0, {"seconds": 9, "value": 2}], "timestamp_utc": "t2"}
    row = compare_file("r.json", json.dumps(old).encode(), json.dumps(new).encode())
    assert row["status"] == "metadata_only" and "run_info" in row["detail"] and "scores[1].seconds" in row["detail"]
    assert strip_json(old) == {"scores": [1.0, {"value": 2}]}
    new["scores"][1]["value"] = 3
    assert compare_file("r.json", json.dumps(old).encode(), json.dumps(new).encode())["status"] == "different"


def test_markdown_masks_generated_line_and_run_sections():
    old = "\n".join(
        ["# T", "", "Generated by `scripts/x.py` at commit `abc` (dirty: False), t1.", "", "## Scores", "", "| a | 1 |",
         "", "## Run", "", "12 s", "", "### Detail", "", "x", "", "## Limits", "", "- y", ""]
    )  # fmt: skip
    new = old.replace("`abc` (dirty: False), t1", "`def` (dirty: True), t2").replace("12 s", "40 s")
    assert compare_file("r.md", old.encode(), new.encode())["status"] == "metadata_only"
    assert "## Limits" in strip_markdown(new) and "40 s" not in strip_markdown(new)
    changed = new.replace("| a | 1 |", "| a | 2 |")
    assert compare_file("r.md", old.encode(), changed.encode())["status"] == "different"


def test_tables_must_be_identical_and_report_the_difference():
    old, new = b"m,v\na,0.5\nb,1\n", b"m,v\na,0.5000001\nb,1\n"
    row = compare_file("s.csv", old, new)
    assert row["status"] == "different" and row["detail"] == "max abs numeric difference 1e-07"
    row = compare_file("s.csv.gz", gzip.compress(old, mtime=0), gzip.compress(new, mtime=0))
    assert row["detail"] == "max abs numeric difference 1e-07"
    assert compare_file("f.png", b"\x89PNG1", b"\x89PNG2")["detail"] == "bytes differ"
    rows = [{"status": "identical"}, {"status": "different"}, {"status": "identical"}]
    assert summarize(rows) == {"identical": 2, "metadata_only": 0, "different": 1, "not_regenerated": 0, "missing": 0}
