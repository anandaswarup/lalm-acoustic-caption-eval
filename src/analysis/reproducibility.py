"""Comparison of regenerated outputs with their committed versions (E22).

A file is reproduced when its bytes equal the committed ones, or when the only differences are run metadata: in
JSON, the keys in METADATA_KEYS at any depth; in Markdown, lines matching METADATA_LINES, the sections in
METADATA_SECTIONS (run timings) and git commit hashes (40 hex digits in backticks; SHA-256 checksums have 64 and stay
compared). Every other file type (CSV, compressed CSV, JSONL, figures, LaTeX) must be
byte-identical. Differences that remain are failures; for CSV tables the largest absolute numeric difference is given.
"""

from __future__ import annotations

import gzip
import io
import json
import re
from pathlib import Path
from typing import Any

import pandas as pd

# Run metadata: where and when a step ran and how long it took, never a result.
METADATA_KEYS = {
    "run_info", "timestamp_utc", "git_commit", "git_dirty", "timing", "timings", "seconds", "elapsed_seconds",
    "duration_seconds_total", "model_load_seconds", "wall_seconds", "durations", "test_output", "integration_tests",
    "platform",
}  # fmt: skip
METADATA_LINES = (
    re.compile(r"^Generated by `scripts/.*` at commit `[0-9a-f]+` \(dirty: (True|False)\)"),
    re.compile(r"^`make test-metrics`: "),
    re.compile(r"^Model loading: [0-9.]+ s\.$"),
)
METADATA_SECTIONS = ("## Run", "## Timing")  # Markdown sections that report run timings only
COMMIT_HASH = re.compile(r"`[0-9a-f]{40}`")  # e.g. the commit an input table was produced at
# Tracked files that `make reproduce` does not write, and why.
NOT_REGENERATED_REASONS = (
    (re.compile(r"^outputs/captions/(evaluation|pilot)/"), "frozen generation output (input; SHA256SUMS checked)"),
    (re.compile(r"_guidelines\.md$"), "hand-written annotation guidelines"),
    (re.compile(r"_reviewer_\d+\.csv$"), "reviewer labels (input)"),
    (re.compile(r"^outputs/qualitative/audio_review_(sheet\.md|manifest\.json)$"),
     "E19 review material: not rebuilt once its templates hold labels; its input checksums are verified by E19"),
)  # fmt: skip

STATUSES = ("identical", "metadata_only", "different", "not_regenerated", "missing")


def strip_json(value: Any) -> Any:
    """`value` without METADATA_KEYS at any depth."""
    if isinstance(value, dict):
        return {k: strip_json(v) for k, v in value.items() if k not in METADATA_KEYS}
    if isinstance(value, list):
        return [strip_json(v) for v in value]
    return value


def json_metadata_paths(value: Any, prefix: str = "") -> list[str]:
    """Paths of the METADATA_KEYS present in `value` (for the report)."""
    paths = []
    if isinstance(value, dict):
        for key, child in value.items():
            path = f"{prefix}.{key}" if prefix else key
            paths += [path] if key in METADATA_KEYS else json_metadata_paths(child, path)
    elif isinstance(value, list):
        for index, child in enumerate(value):
            paths += json_metadata_paths(child, f"{prefix}[{index}]")
    return paths


def strip_markdown(text: str) -> str:
    """Markdown without METADATA_LINES and without the METADATA_SECTIONS (up to the next heading of the same
    or a higher level)."""
    out, skipping = [], 0
    for line in text.splitlines():
        heading = re.match(r"^(#+) ", line)
        if heading and skipping and len(heading.group(1)) <= skipping:
            skipping = 0
        if any(line == section or line.startswith(section + " ") for section in METADATA_SECTIONS):
            skipping = len(line.split(" ")[0])
            continue
        if skipping or any(pattern.match(line) for pattern in METADATA_LINES):
            continue
        out.append(COMMIT_HASH.sub("`<commit>`", line))
    return "\n".join(out)


def _read_csv(data: bytes, gz: bool) -> pd.DataFrame:
    return pd.read_csv(io.BytesIO(gzip.decompress(data) if gz else data), keep_default_na=False)


def max_numeric_difference(old: bytes, new: bytes, gz: bool) -> float | None:
    """Largest absolute difference between numeric cells of two same-shaped CSV tables (None if not comparable)."""
    try:
        a, b = _read_csv(old, gz), _read_csv(new, gz)
    except Exception:  # noqa: BLE001 - not a table
        return None
    if a.shape != b.shape or list(a.columns) != list(b.columns):
        return None
    largest = 0.0
    for column in a.columns:
        x, y = pd.to_numeric(a[column], errors="coerce"), pd.to_numeric(b[column], errors="coerce")
        both = x.notna() & y.notna()
        if both.any():
            largest = max(largest, float((x[both] - y[both]).abs().max()))
    return largest


def compare_file(path: str, old: bytes | None, new: bytes | None) -> dict[str, Any]:
    """Status of one file and, when it is not identical, what differs."""
    row: dict[str, Any] = {"path": path, "status": "", "detail": ""}
    if new is None:
        return {**row, "status": "missing", "detail": "committed file absent after the run"}
    if old == new:
        return {**row, "status": "identical"}
    suffixes = "".join(Path(path).suffixes[-2:])
    if path.endswith(".json"):
        a, b = json.loads(old), json.loads(new)
        if strip_json(a) == strip_json(b):
            masked = sorted(set(json_metadata_paths(a)) | set(json_metadata_paths(b)))
            return {**row, "status": "metadata_only", "detail": "masked: " + ", ".join(masked)}
        return {**row, "status": "different", "detail": "JSON content differs outside run metadata"}
    if path.endswith(".md"):
        if strip_markdown(old.decode()) == strip_markdown(new.decode()):
            return {**row, "status": "metadata_only", "detail": "masked: generated-by line, run/timing sections"}
        return {**row, "status": "different", "detail": "Markdown differs outside run metadata"}
    if suffixes.endswith(".csv") or suffixes.endswith(".csv.gz"):
        largest = max_numeric_difference(old, new, path.endswith(".gz"))
        detail = "not comparable as tables" if largest is None else f"max abs numeric difference {largest:.3g}"
        return {**row, "status": "different", "detail": detail}
    return {**row, "status": "different", "detail": "bytes differ"}


def not_regenerated_reason(path: str) -> str:
    return next((reason for pattern, reason in NOT_REGENERATED_REASONS if pattern.search(path)), "no reason recorded")


def summarize(rows: list[dict[str, Any]]) -> dict[str, int]:
    return {status: sum(row["status"] == status for row in rows) for status in STATUSES}


def report_markdown(report: dict[str, Any]) -> str:
    counts, env = report["counts"], report["environment"]
    passed = counts["different"] == 0 and counts["missing"] == 0
    lines = [
        "# Reproducibility check (E22)",
        "",
        f"Generated by `scripts/check_reproducibility.py`, {report['timestamp_utc']}. Outputs regenerated by "
        f"`make reproduce` in a fresh clone of commit `{report['reproduced_at']}` and compared with the committed "
        f"outputs of `{report['commit']}`"
        + (" (identical to those of the reproduced commit)." if report["same_committed_outputs"] else "."),
        "",
        f"**Result: {'reproduced' if passed else 'NOT reproduced'}.** {counts['identical']} files byte-identical, "
        f"{counts['metadata_only']} differ only in run metadata, {counts['different']} differ, {counts['missing']} "
        f"missing, {counts['not_regenerated']} not regenerated by `make reproduce`.",
        "",
        "## Procedure",
        "",
        *[f"{i}. {step}" for i, step in enumerate(report["procedure"], start=1)],
        "",
        "## Environment",
        "",
        *[f"- {key}: {value}" for key, value in env.items() if not isinstance(value, (list, dict))],
        f"- Packages: `{report['outputs']['environment']}` lists both environments (`uv pip freeze`).",
        "",
        "## Criterion and masked metadata",
        "",
        "A file is reproduced if it is byte-identical to the committed version, or if JSON and Markdown reports "
        "differ only in run metadata: the JSON keys "
        + ", ".join(f"`{k}`" for k in sorted(report["metadata_keys"]))
        + "; in Markdown, the generated-by line (commit, dirty flag, time), the integration-test summary line, "
        "model loading time, git commit hashes (40 hex digits; SHA-256 checksums stay compared) and the sections "
        + ", ".join(f"`{s}`" for s in report["metadata_sections"])
        + ". Everything else (scores, tables, figures, manifests, captions) must be byte-identical; there is no "
        "numerical tolerance.",
        "",
        "Nondeterminism observed: only run metadata (timestamps, commit hashes, including the commit recorded for an "
        "upstream input table, the dirty flag, which is true for every step after the first because earlier steps "
        "rewrite tracked files, durations, and the platform string, which records the OS version).",
        "",
        "## Files",
        "",
        "| Status | Files |",
        "|---|---|",
        *[f"| {status} | {counts[status]} |" for status in STATUSES],
        "",
    ]
    for status in ("different", "missing", "metadata_only", "not_regenerated"):
        rows = [row for row in report["files"] if row["status"] == status]
        if rows:
            lines += [f"### {status.replace('_', ' ').capitalize()}", ""]
            lines += [f"- `{row['path']}`" + (f": {row['detail']}" if row["detail"] else "") for row in rows]
            lines.append("")
    lines += [
        "### Identical",
        "",
        f"{counts['identical']} files; the full list is in `{report['outputs']['report_json']}`.",
        "",
    ]
    return "\n".join(lines)
